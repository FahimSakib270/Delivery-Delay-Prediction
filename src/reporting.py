"""Generate report/model/data cards from the same artifacts as the demo."""
from __future__ import annotations
import json
from .config import resolve


def markdown_table(frame, columns):
    lines = ["| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    for _, row in frame.iterrows():
        values = [f"{row[c]:.4f}" if isinstance(row[c], float) else str(row[c]) for c in columns]
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines)


def write_reports(cfg, summary, comparison, exploratory, policies):
    reports = resolve(cfg, "paths", "reports_dir")
    manifest = json.loads((reports / "run_manifest.json").read_text())
    metadata = json.loads((resolve(cfg, "paths", "processed_dir") / "dataset_metadata.json").read_text())
    stats = metadata["statistics"]
    metrics = summary["test_metrics"]
    model = manifest["model"]
    params = model["hyperparameters"][model["name"]]["best_params"]
    source = summary["data_source"]["kind"]
    warning = ("SYNTHETIC SOFTWARE DEMONSTRATION: no evidence about real deliveries." if summary["data_source"]["synthetic"]
               else "Real Olist data: Brazilian marketplace orders, not Bangladesh courier or ProFast operational data.")
    periods = manifest["splits"]["split"]["periods"]
    results_link = "Full metrics and bootstrap intervals: [results_summary.md](results_summary.md)."
    common = f"""<!-- generated by python -m src.evaluate; do not edit measured values by hand -->

{warning}

Protocol: `{manifest['experiment_protocol']}`. Seed: {cfg['project']['random_seed']}.

This is a corrected retrospective rerun. The historical test outcomes were already
inspected during project development. They are held out from the automated selection
functions, but are not a fresh, never-seen confirmation set. Future work requires
rolling-origin evaluation and a new prospective holdout.
"""
    model_card = f"""# Model card — booking-time delivery-delay risk
{common}
## Model and decision

- Selected model: **{model['name']}**.
- Tuned parameters, read from the run manifest: `{params}`.
- Preprocessing: training-fitted numerical imputation, scaling for logistic regression,
  and categorical imputation/one-hot encoding with unseen-category handling.
- Experimental threshold: **{model['threshold']:.4f}**, selected by validation F1.
- Training rows: {manifest['splits']['folds_after_maturity']['train']['n_rows']:,}.
- Artifact: `models/best_model.joblib`; pipeline, feature schema, threshold, split
  metadata and processed-data checksum are stored together.
- Output: **uncalibrated risk score**, not a reliable probability or action recommendation.

## Measured evaluation

Test rows: {int(metrics['n']):,}; delayed prevalence: {metrics['prevalence']:.4f}.
Average precision: {metrics['average_precision']:.4f}; ROC-AUC: {metrics['roc_auc']:.4f}.
Precision: {metrics['precision']:.4f}; recall: {metrics['recall']:.4f}; F1: {metrics['f1']:.4f}.
Confusion: TP {int(metrics['tp'])}, FP {int(metrics['fp'])}, FN {int(metrics['fn'])}, TN {int(metrics['tn'])}.
Raw ECE: {summary['calibration_ece']:.4f}.

{results_link}

## Intended use and limits

An educational research prototype for ranking completed orders using booking-time
inputs. It is not validated for live deployment, price changes, customer eligibility,
or promises about individual deliveries. Geography and parcel characteristics may
create unequal error rates; review subgroup reports before considering a pilot.

Class weighting changes the training objective and can distort probability estimates.
Validation-fitted isotonic calibration is a separate exploratory analysis, not part
of the serving bundle. Its test ECE is {exploratory['calibrated_ece']:.4f}; its test AP
is {exploratory['calibrated_test']['average_precision']:.4f}. Isotonic mappings can
introduce ties, so ranking metrics are recomputed rather than assumed unchanged.

Costs are hypothetical error penalties. No intervention effect, profit, or operational
saving was measured. The seven-day rule is a candidate for further validation and a
controlled pilot, not a deployment recommendation.
"""
    data_card = f"""# Data card — booking-time delivery-delay study
{common}
## Source

Dataset: Brazilian E-Commerce Public Dataset by Olist.
Publisher page: https://www.kaggle.com/datasets/olistbr/brazilian-ecommerce
Download endpoint: https://www.kaggle.com/api/v1/datasets/download/olistbr/brazilian-ecommerce
Published data license: CC BY-NC-SA 4.0; verify the publisher's current terms before reuse.
Retrieval/preparation details, file checksums, row counts and exclusions are in
`data_prep_manifest.json`. Raw data is excluded from git.

For synthetic runs, the Olist-shaped generator is a software fixture, not a sample of
actual Brazilian or Bangladeshi orders. Its provenance is explicitly recorded.

## Records and exclusions

Raw orders: {stats['raw_orders']:,}; retained completed orders: {stats['final_orders']:,}.
Retained delayed fraction: {stats['late_rate']:.4f}.
Canceled/unavailable exclusions: {stats['dropped_canceled_or_unavailable']:,}.
Unresolved/missing delivery exclusions: {stats['dropped_unresolved_no_delivery_date']:,}.
Booking range: {stats['booking_period']['start']} to {stats['booking_period']['end']}.
Other exclusions and missing values are recorded in the preparation manifest.

Excluding unresolved orders creates selection bias: the model is evaluated on completed
orders and does not cover lost, canceled, or still-outstanding orders.

## Target and feature availability

Primary target: delivery calendar date strictly later than promised calendar date.
Delivery on the promised day is on time. The timestamp-based label is a sensitivity
check; a promise stored at midnight is not interpreted as a midnight deadline.

Delivery timestamps, order status, reviews, identifiers, and approval/payment events
are not model inputs. See `feature_audit.csv` for the feature-by-feature audit.
The promise and catalog/item information are assumed available at checkout; snapshot
availability cannot be fully proven from this retrospective dataset.

Item rows are aggregated to one row per order. Prices, freight, weight and volume are
summed. Product and seller counts are distinct counts. A representative category/state
is selected in item-ID order; missing representative values can come from a later item.
Geography reflects the representative seller, not every seller in a multi-seller order.
Missing summed physical measurements may become zero; this remains a data-quality limit.

## Temporal evaluation

Train/validation/test boundaries follow booking time, approximately 70/15/15.
Identical booking timestamps stay together. Training outcomes must have actual delivery
timestamps strictly before validation begins. Validation outcomes used for selection
must be observed before test begins. Inner expanding-window CV applies the same actual
training-delivery check at each fold's first validation booking. These filters introduce
additional selection effects and their removal counts are recorded in the manifests.

Test labels are scored retrospectively after delivery; they are not required to be
available at booking. No future delivery timestamp is supplied to a predictor.

## External validity and privacy

2016–2018 Brazilian marketplace operations differ from Bangladesh courier services.
Performance cannot be transferred without local data and validation. Anonymized IDs and
location fields are not a guarantee of zero re-identification risk; avoid publishing
additional raw records or using outputs for customer discrimination.
"""
    comparison_text = markdown_table(comparison, ["model", "split", "average_precision", "roc_auc"])
    policy_text = markdown_table(policies, ["policy", "flag_rate", "precision", "recall", "hypothetical_cost_per_1000"])
    tech = f"""# Technical report — ProFast delivery-delay prediction
{common}
## 1. Abstract

This standalone prototype studies whether booking-time information can rank orders by
risk of arriving after their promised date. It is inspired by ProFast, an undergraduate
MERN package-management system; no production integration is claimed. The preparation
pipeline retained {stats['final_orders']:,} completed orders. The selected
{model['name']} achieved test AP {metrics['average_precision']:.4f} against prevalence
{metrics['prevalence']:.4f}, and precision/recall {metrics['precision']:.4f}/{metrics['recall']:.4f}
at the validation-selected threshold. These results demonstrate a limited retrospective
ranking signal, not evidence of deployment readiness.

## 2. Problem and dataset

Prediction occurs at booking, after a promised delivery date has been assigned.
The target is binary calendar-date lateness, not travel duration. Only booking-time
features enter the model. The data and feature assumptions, exclusions, and geographic
limits are documented in [data_card.md](data_card.md).

## 3. Method

The candidates are a majority-class dummy, class-weighted logistic regression, and a
class-weighted random forest. Learned preprocessing is inside each sklearn pipeline,
so it is fitted only on fold training data. Hyperparameters use expanding-window CV
with actual delivery-time maturity checks, and model selection uses validation AP.
Average precision summarizes the precision-recall ranking; it is not trapezoidal PR-AUC.
ROC-AUC measures positive-negative ranking and is not automatically inflated by low
prevalence, but does not directly report operational precision at a rare base rate.
Accuracy is compared against the majority-class baseline rather than used alone.

Booking boundaries: train ends {periods['train_end']}; validation starts
{periods['validation_start']}; test starts {periods['test_start']}.
Each CV fold's row counts and latest training delivery are saved in
`hyperparameter_search.json`. Tied booking instants never straddle an outer or inner
boundary. The primary threshold maximizes validation F1; it is not a commercially
optimized decision. Candidate test diagnostics occur after selection is frozen.

## 4. Results

{comparison_text}

{results_link}

Bootstrap intervals resample test rows and assume exchangeability. They do not capture
all temporal or seller/customer dependence, model-selection uncertainty, or deployment
shift. They should not be used alone to claim statistical proof of real-world utility.

## 5. Error analysis

`test_subgroups.csv` reports region, promise-length, basket, route and month slices,
with small-group warnings. `error_examples_false_positives.csv` and
`error_examples_false_negatives.csv` expose concrete failures. Permutation importance
on the test period is descriptive post-evaluation analysis, not a feature-selection
step or proof of causal influence. Early EDA figures use development data only.

## 6. Reproducible exploratory calibration and policy analysis

Run `python -m src.experiments` after training, or use `src.evaluate` which invokes it.
Validation predictions are saved alongside test predictions. Isotonic regression is
fitted on validation outcomes only; test outcomes never fit the calibrator. This is
retrospective exploration after prior inspection of the historical test data.

Raw test ECE: {exploratory['raw_ece']:.4f}; calibrated ECE: {exploratory['calibrated_ece']:.4f}.
Raw AP: {exploratory['raw_test']['average_precision']:.4f}; calibrated AP:
{exploratory['calibrated_test']['average_precision']:.4f}. Raw ROC-AUC:
{exploratory['raw_test']['roc_auc']:.4f}; calibrated ROC-AUC:
{exploratory['calibrated_test']['roc_auc']:.4f}. Ranking is measured again because
isotonic calibration may introduce equal-score ties. Calibration is not shipped in
the demo model bundle; the interface displays an uncalibrated score without advice.

Assumed false-negative cost: {cfg['business_case']['cost_false_negative']}; assumed
false-positive cost: {cfg['business_case']['cost_false_positive']}, in arbitrary units.
This penalty calculation assumes flagged late orders avoid a miss penalty and has no
measured contact cost or intervention success rate. It is not measured profit.

{policy_text}

Top-up budgets and the seven-day rule are fixed configuration values, not optimized
on test outcomes. Random top-ups use the exact expected counts for uniform sampling
of remaining orders. Model top-ups use raw ranking scores with deterministic tie
handling. The resulting comparisons are exploratory and do not justify deployment.

## 7. Limitations and next steps

- A single historical split and previously inspected test outcomes; use rolling-origin
  backtests and a new prospective holdout for confirmation.
- Completed-order and maturity filtering introduce selection bias.
- Uncalibrated serving scores and potential temporal distribution shift.
- Retrospective catalog/checkout feature availability is an assumption.
- Hypothetical costs and no causal evidence that intervention improves outcomes.
- Dataset-specific geography, promise policy, and 2016–2018 marketplace conditions.

Evaluate the simple promise-length rule through further backtesting and a controlled
pilot. Collect real ProFast/Bangladesh data before claiming local usefulness. Fit and
assess calibration under a prespecified protocol before serving probabilities. Improve
measurement missingness handling and audit subgroup error rates.

## 8. Reproduction and references

`python -m src.prepare`, `python -m src.train`, `python -m src.evaluate`.
Use `--config config/synthetic.yaml` for a separate software demonstration.
Pinned dependencies, file checksums, configuration, protocol, environment and code
commit are recorded. Runtime and small floating-point differences may vary by machine.

- Olist dataset: https://www.kaggle.com/datasets/olistbr/brazilian-ecommerce
- sklearn model selection: https://scikit-learn.org/stable/modules/cross_validation.html
- sklearn calibration: https://scikit-learn.org/stable/modules/calibration.html
- sklearn metrics: https://scikit-learn.org/stable/modules/model_evaluation.html
"""
    for name, content in [("model_card.md", model_card), ("data_card.md", data_card), ("technical_report.md", tech)]:
        (reports / name).write_text(content, encoding="utf-8")
